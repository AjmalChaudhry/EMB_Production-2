import { Injectable } from '@angular/core';
import { HttpClient, HttpParams } from '@angular/common/http';
import { Observable } from 'rxjs';

import { ProductForm, ProductDto, ProductListViewModel } from '../models/product.dto';
import {
  ApiResponse,
  ApiResponseData
} from '../shared/models/api-response';

@Injectable({ providedIn: 'root' })
export class GenProductService {

  // Matches MVC route prefix
  private baseUrl = `${window.location.origin}/emb-products/products`;

  constructor(private http: HttpClient) { }

  // ============================================================
  // LIST PAGED
  // GET → /emb-products/products/listPaged
  // ============================================================
  listPaged(
    search: string = '',
    page: number = 1,
    pageSize: number = 10
  ): Observable<{ success: boolean; total: number; items: ProductListViewModel[] }> {

    const params = new HttpParams()
      .set('search', search ?? '')
      .set('page', page.toString())
      .set('pageSize', pageSize.toString());

    return this.http.get<{ success: boolean; total: number; items: ProductListViewModel[] }>(
      `${this.baseUrl}/listPaged`,
      {
        params,
        withCredentials: true
      }
    );
  }

  // ============================================================
  // CATEGORIES
  // GET → /emb-products/products/categories
  // ============================================================
  getCategories(): Observable<{ id: number; name: string }[]> {
    return this.http.get<{ id: number; name: string }[]>(
      `${this.baseUrl}/categories`,
      { withCredentials: true }
    );
  }

  // ============================================================
  // BRANCHES
  // GET → /emb-products/products/branches
  // ============================================================
  getBranches(): Observable<{ id: number; name: string }[]> {
    return this.http.get<{ id: number; name: string }[]>(
      `${this.baseUrl}/branches`,
      { withCredentials: true }
    );
  }

  // ============================================================
  // OPTIONAL: NEXT AUTO CODE PREVIEW
  // GET → /emb-products/products/next-code
  // ============================================================
  getNextCode(): Observable<ApiResponseData<{ code: string }>> {
    return this.http.get<ApiResponseData<{ code: string }>>(
      `${this.baseUrl}/next-code`,
      { withCredentials: true }
    );
  }

  // ============================================================
  // PRODUCTS FOR PURCHASE
  // GET → /emb-products/products/products-for-purchase
  // ============================================================
  getProductsForPurchase(): Observable<ApiResponseData<any[]>> {
    return this.http.get<ApiResponseData<any[]>>(
      `${this.baseUrl}/products-for-purchase`,
      { withCredentials: true }
    );
  }

  // ============================================================
  // CREATE
  // POST → /emb-products/products/create
  // Product code is auto-generated by backend
  // ============================================================
  create(product: ProductForm): Observable<ApiResponse> {
    const payload: ProductForm = {
      ...product,
      id: null,
      prodCode: '' // let backend generate it
    };

    return this.http.post<ApiResponse>(
      `${this.baseUrl}/create`,
      payload,
      { withCredentials: true }
    );
  }

  // ============================================================
  // UPDATE
  // POST → /emb-products/products/update/{id}
  // ============================================================
  update(product: ProductForm): Observable<ApiResponse> {
    if (!product.id || product.id <= 0) {
      throw new Error('Product ID is required for update');
    }

    return this.http.post<ApiResponse>(
      `${this.baseUrl}/update/${product.id}`,
      product,
      { withCredentials: true }
    );
  }

  // ============================================================
  // DETAIL
  // GET → /emb-products/products/detail/{id}
  // ============================================================
  getDetail(id: number): Observable<ApiResponseData<ProductDto>> {
    return this.http.get<ApiResponseData<ProductDto>>(
      `${this.baseUrl}/detail/${id}`,
      { withCredentials: true }
    );
  }

  // ============================================================
  // DELETE
  // POST → /emb-products/products/delete
  // ============================================================
  delete(id: number): Observable<ApiResponse> {
    return this.http.post<ApiResponse>(
      `${this.baseUrl}/delete`,
      { id },
      { withCredentials: true }
    );
  }
}
