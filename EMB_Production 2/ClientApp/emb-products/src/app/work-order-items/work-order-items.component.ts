  filterFromDate = '';
  filterToDate = '';
  filterWorkOrderId: number | null = null;
  filterBranchId: number | null = null;
  filterStatus = '';

  summary = {
    count: 0,
    totalQty: 0,
    totalCompletedQty: 0,
    totalRejectedQty: 0,
    totalAmount: 0,
    totalCost: 0,
    byStatus: [] as Array<{ status: string; count: number }>
  };

