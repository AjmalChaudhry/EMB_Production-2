  openModal(el?: ElementRef): void {
    if (!el?.nativeElement) return;

    const existing = bootstrap.Modal.getInstance(el.nativeElement);
    if (existing) {
      existing.show();
      return;
    }

    const modal = new bootstrap.Modal(el.nativeElement, {
      backdrop: 'static',
      keyboard: false
    });

    modal.show();
  }

  closeModal(el?: ElementRef): void {
    if (!el?.nativeElement) return;

    const modal = bootstrap.Modal.getInstance(el.nativeElement);
    modal?.hide();
  }

