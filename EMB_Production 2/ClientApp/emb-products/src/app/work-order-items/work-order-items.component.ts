  getSelectedProductName(): string {
    const workOrderId = Number(this.formModel?.workOrderId ?? 0);

    const wo = (this.workOrders || []).find(
      x => Number(x?.id ?? 0) === workOrderId
    );

    const nameFromWO =
      wo?.productName ??
      (wo as any)?.ProductName ??   // fallback if API sends PascalCase
      null;

    const fallbackName =
      this.getProductName(this.formModel?.productId);

    return (nameFromWO || fallbackName || '-').trim();
  }

  getJobOrderName(id: number | null | undefined): string {
    return this.getLookupName(this.jobOrders, id);
  }

  getDesignName(id: number | null | undefined): string {
    const selected = this.designs.find(x => x.id === id);
    if (!selected) return '-';
    return selected.code ? `${selected.code} - ${selected.name}` : selected.name;
  }

  getProductName(id: number | null): string {
    if (!id) return '';

    const p = this.products.find(x => Number(x?.id ?? 0) === id);
    return p?.name ?? '';
  }

  getBranchName(id: number | null | undefined): string {
    return this.getLookupName(this.branches, id);
  }

  getMachineName(id: number | null | undefined): string {
    return this.getLookupName(this.machines, id);
  }

  getComponentName(id: number | null | undefined): string {
    return this.getLookupName(this.components, id);
  }

  private getLookupName(list: LookupItem[], id: number | null | undefined): string {
    if (!id) return '-';
    return list.find(x => x.id === id)?.name ?? '-';
  }

  ConvertJsonDate(value: any): string {
    if (!value) return '—';

    if (typeof value === 'string' && value.startsWith('/Date(')) {
      const t = parseInt(value.replace('/Date(', '').replace(')/', ''), 10);
      return isNaN(t) ? '—' : new Date(t).toISOString().substring(0, 10);
    }

    if (typeof value === 'string' && /^\d{4}-\d{2}-\d{2}/.test(value)) {
      return value.substring(0, 10);
    }

    const dt = new Date(value);
    return isNaN(dt.getTime()) ? '—' : dt.toISOString().substring(0, 10);
  }

